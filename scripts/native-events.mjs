#!/usr/bin/env node
// Writes packages/vite-plugin-yield/src/native-events.js: each event attribute
// Solid's JSX types (`onPointerDown?: EventHandlerUnion<T, PointerEvent>`),
// its event type and its handler's kind (an input, change or focus handler's
// `target` is the element when it is a form control). The lowering types a
// handler's parameter from it without asking TypeScript to resolve Solid's
// attribute interfaces (the cost of every handler, D-124). `--check` fails
// when the installed @solidjs/web types say otherwise (native-events.test.js).
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const require = createRequire(join(root, "packages/vite-plugin-yield/package.json"));
const ts = require("typescript");
const web = dirname(dirname(require.resolve("@solidjs/web")));
const jsx = join(web, "types/jsx.d.ts");
const version = JSON.parse(readFileSync(join(web, "package.json"), "utf8")).version;

/** @returns {Record<string, [string, string]>} attribute → [event type, handler kind] */
export function solidEvents() {
  const source = ts.createSourceFile(jsx, readFileSync(jsx, "utf8"), ts.ScriptTarget.Latest, true);
  const kinds = {
    EventHandlerUnion: "plain",
    InputEventHandlerUnion: "input",
    ChangeEventHandlerUnion: "change",
    FocusEventHandlerUnion: "focus"
  };
  /** @type {Record<string, [string, string]>} */
  const events = {};
  const visit = node => {
    if (ts.isPropertySignature(node) && /^on[A-Z]/.test(node.name.getText(source)) && node.type) {
      const members = ts.isUnionTypeNode(node.type) ? node.type.types : [node.type];
      for (const member of members) {
        if (!ts.isTypeReferenceNode(member)) continue;
        const kind = kinds[member.typeName.getText(source)];
        const event = member.typeArguments?.[1]?.getText(source);
        if (!kind || !event) continue;
        const name = node.name.getText(source);
        const seen = events[name];
        if (seen && (seen[0] !== event || seen[1] !== kind))
          throw new Error(`${name} is typed twice: ${seen} and ${[event, kind]}`);
        events[name] = [event, kind];
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(source);
  return Object.fromEntries(Object.entries(events).sort(([a], [b]) => a.localeCompare(b)));
}

/** The event types the DOM's own library declares (the rest are Solid's or newer). */
export function globalEvents(names) {
  const file = "/events.ts";
  const text = names.map((n, i) => `type _${i} = ${n};`).join("\n");
  const options = {
    strict: true,
    noEmit: true,
    lib: ["lib.esnext.d.ts", "lib.dom.d.ts"],
    types: []
  };
  const host = ts.createCompilerHost(options);
  const read = host.readFile,
    exists = host.fileExists,
    get = host.getSourceFile;
  host.readFile = p => (p === file ? text : read(p));
  host.fileExists = p => p === file || exists(p);
  host.getSourceFile = (p, v) => (p === file ? ts.createSourceFile(p, text, v) : get(p, v));
  const program = ts.createProgram([file], options, host);
  const missing = new Set(
    ts.getPreEmitDiagnostics(program).map(d => {
      const line = d.file && ts.getLineAndCharacterOfPosition(d.file, d.start ?? 0).line;
      return names[line ?? -1];
    })
  );
  return new Set(names.filter(n => !missing.has(n)));
}

export function render() {
  const events = solidEvents();
  const global = globalEvents([...new Set(Object.values(events).map(([e]) => e))]);
  const rows = Object.entries(events).map(
    ([name, [event, kind]]) =>
      `  ${name}: [${JSON.stringify(global.has(event) ? event : null)}, "${kind}"]`
  );
  return `// Generated by scripts/native-events.mjs from @solidjs/web ${version}'s JSX types: do
// not edit. Each event attribute: [its event type when the DOM's own library
// declares it (else null: the lowering asks Solid's types), its handler's kind].
/** @type {Record<string, [string | null, "plain" | "input" | "change" | "focus"]>} */
export const SOLID_EVENTS = {
${rows.join(",\n")}
};
`;
}

if (process.argv[1] === resolve(import.meta.filename)) {
  const out = join(root, "packages/vite-plugin-yield/src/native-events.js");
  const text = render();
  if (process.argv.includes("--check")) {
    if (readFileSync(out, "utf8") !== text) {
      console.error("native-events.js is stale: run node scripts/native-events.mjs");
      process.exit(1);
    }
    console.log("native-events.js matches @solidjs/web " + version);
  } else {
    writeFileSync(out, text);
    console.log(
      `native-events.js: ${Object.keys(solidEvents()).length} event attributes (@solidjs/web ${version})`
    );
  }
}
