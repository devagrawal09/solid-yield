#!/usr/bin/env node
// Regenerates the vendored JSX types (jsx/jsx-properties.d.ts, jsx/jsx.d.ts)
// from the installed @solidjs/web, so a Solid RC bump regenerates them:
//
//   pnpm --filter solid-blocks run types:jsx
//
// In the Solid fork these were built from ../web's sources (jsx-h.d.ts through
// web's scripts/jsx-sync.mjs --compile). Published @solidjs/web ships that
// script's compiled output (types/jsx.d.ts, element `SolidElement | Node |
// ArrayElement`) and jsx-properties.d.ts, so this script re-stamps the compiled
// namespace for blocks: the solid-js `Element` import becomes blocks' own and
// `JSX.Element` becomes `BlocksElement` — the same two edits jsx-sync's
// `--element` / `--import` made. scripts/jsx-web-shared.mjs then runs as before
// (web's own SerializableAttributeValue brand; D-067's `ElementType`).
//
// The outputs are checked in; regenerate and commit them when Solid moves.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(path.join(root, "package.json"));

/** The installed @solidjs/web's directory (it exports no ./package.json). */
function webRoot() {
  let dir = path.dirname(require.resolve("@solidjs/web"));
  for (;;) {
    const pkg = path.join(dir, "package.json");
    if (fs.existsSync(pkg) && JSON.parse(fs.readFileSync(pkg, "utf8")).name === "@solidjs/web")
      return dir;
    const up = path.dirname(dir);
    if (up === dir) throw new Error("jsx-from-web: @solidjs/web's package root not found");
    dir = up;
  }
}

const web = webRoot();
const { version } = JSON.parse(fs.readFileSync(path.join(web, "package.json"), "utf8"));
const out = path.join(root, "jsx");
fs.mkdirSync(out, { recursive: true });

fs.copyFileSync(path.join(web, "types/jsx-properties.d.ts"), path.join(out, "jsx-properties.d.ts"));

let source = fs.readFileSync(path.join(web, "types/jsx.d.ts"), "utf8");

const banner = /^\/\*\*\n \* THIS FILE IS GENERATED[\s\S]*?\*\/\n/;
if (!banner.test(source)) throw new Error("jsx-from-web: generated-file banner not found");
source = source.replace(
  banner,
  () =>
    "/**\n" +
    " * THIS FILE IS GENERATED by `scripts/jsx-from-web.mjs` (then `scripts/jsx-web-shared.mjs`)\n" +
    ` * from @solidjs/web@${version}'s types/jsx.d.ts. Do not edit; run \`pnpm run types:jsx\`.\n` +
    " */\n"
);

const solidImport = 'import type { Element as SolidElement } from "solid-js";';
if (!source.includes(solidImport))
  throw new Error("jsx-from-web: solid-js Element import not found");
source = source.replace(
  solidImport,
  () => 'import type { Element as BlocksElement } from "solid-blocks";'
);

const element =
  /type Element =[\s\S]*?\n  \/\/ END - difference between `jsx\.d\.ts` and `jsx-h\.d\.ts`/;
if (!element.test(source)) throw new Error("jsx-from-web: JSX.Element declaration block not found");
source = source.replace(
  element,
  () => "type Element = BlocksElement;\n  // END - difference between `jsx.d.ts` and `jsx-h.d.ts`"
);

fs.writeFileSync(path.join(out, "jsx.d.ts"), source);
console.log(`jsx-from-web: jsx/ regenerated from @solidjs/web@${version}`);
